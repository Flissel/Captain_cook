"""Local helper for the OpenClaw planner spike (plan 2026-11-07, Phase 5).

Everything runs against a throwaway ledger (own Compose project, port 3307)
with freshly generated secrets in `deploy/captain-openclaw/.env`, which is
gitignored. Secret values are never printed.

    python scripts/openclaw_spike.py init-env
    python scripts/openclaw_spike.py gateway      # Captain gateway on :8090
    python scripts/openclaw_spike.py mcp          # Captain MCP server on :8121
    python scripts/openclaw_spike.py seed-batch   # one pending work_batch
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import secrets
import sys
from pathlib import Path
from urllib.parse import quote

ENV_PATH = Path(__file__).resolve().parents[1] / "deploy" / "captain-openclaw" / ".env"
SPIKE_AGENT_ID = "openclaw"


class SpikeEnvExistsError(RuntimeError):
    """Refuse to replace secrets another run may already depend on."""


def _secret() -> str:
    return secrets.token_urlsafe(32)


def init_env(path: Path = ENV_PATH) -> None:
    if path.exists():
        raise SpikeEnvExistsError(f"{path} already exists; delete it deliberately to regenerate")
    mariadb_password = _secret()
    agent_token = _secret()
    values = {
        # OpenClaw container
        "OPENCLAW_GATEWAY_TOKEN": _secret(),
        "CAPTAIN_MCP_TOKEN": _secret(),
        # Captain MCP server -> gateway, as the registered agent "openclaw"
        "CAPTAIN_MCP_GATEWAY_TOKEN": agent_token,
        "CAPTAIN_GATEWAY_URL": "http://127.0.0.1:8090",
        # Throwaway ledger (docker-compose.yml mariadb, own project, port 3307)
        "MARIADB_PORT": "3307",
        "MARIADB_DATABASE": "ledger",
        "MARIADB_USER": "captain",
        "MARIADB_PASSWORD": mariadb_password,
        "MARIADB_ROOT_PASSWORD": _secret(),
        # Gateway
        "LEDGER_DSN": f"mariadb://captain:{quote(mariadb_password, safe='')}@127.0.0.1:3307/ledger",
        "CAPTAIN_GATEWAY_TOKEN": _secret(),
        "WORKER_GATEWAY_TOKEN": _secret(),
        "CAPTAIN_RUNTIME_URL": "http://127.0.0.1:9",
        "CAPTAIN_RUNTIME_TOKEN": _secret(),
        "WORKER_AGENT_TOKEN_SHA256_JSON": json.dumps(
            {SPIKE_AGENT_ID: hashlib.sha256(agent_token.encode("utf-8")).hexdigest()}
        ),
        "GATEWAY_REQUIRE_AGENT_IDENTITY": "true",
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# Generated by scripts/openclaw_spike.py init-env. Never commit.", ""]
    lines += [f"{name}={value}" for name, value in values.items()]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(values)} spike settings to {path}")


def read_env(path: Path = ENV_PATH) -> dict[str, str]:
    values: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        name, _, value = stripped.partition("=")
        values[name.strip()] = value
    return values


def _load_into_process(path: Path) -> None:
    if not path.exists():
        raise SystemExit(f"{path} is missing; run init-env first")
    os.environ.update(read_env(path))


def _run_gateway() -> None:
    from gateway.app import main

    main()


def _run_mcp() -> None:
    from agenten.captain_mcp.server import main

    main()


def _seed_batch() -> None:
    import httpx

    response = httpx.post(
        f"{os.environ['CAPTAIN_GATEWAY_URL']}/blocks",
        headers={"Authorization": f"Bearer {os.environ['CAPTAIN_GATEWAY_TOKEN']}"},
        json={
            "block_type": "work_batch",
            "status": "pending",
            "data": {
                "batch_id": "spike-batch-1",
                "title": "OpenClaw spike: read me through MCP",
                "goal": "Prove that OpenClaw can read Captain batches",
                "subtask_ids": ["spike-subtask-1"],
                "target": "python",
                "capability_tags": ["spike"],
                "acceptance_criteria": [
                    {"assertion_id": "spike-read", "kind": "status_equals", "expected": "succeeded"}
                ],
            },
        },
        timeout=30,
    )
    print(f"seed-batch: gateway status {response.status_code}")
    if response.status_code not in {200, 201}:
        raise SystemExit(1)


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=["init-env", "gateway", "mcp", "seed-batch"])
    parser.add_argument("--env-file", type=Path, default=ENV_PATH)
    args = parser.parse_args(argv)
    if args.command == "init-env":
        init_env(args.env_file)
        return
    _load_into_process(args.env_file)
    {"gateway": _run_gateway, "mcp": _run_mcp, "seed-batch": _seed_batch}[args.command]()


if __name__ == "__main__":
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
    main()
